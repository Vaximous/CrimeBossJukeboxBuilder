"""Part A of the guide: turn the Wwise project into the mod's audio pak.

Runs entirely on the Crime Boss Mod Kit's own engine (no stock UE 4.27 / Visual Studio):
each mod gets its own copy of the guide's JukeboxTemplate project, with the Mod Kit's
pre-built Wwise plugin dropped in. Then, headless:

  1. GenerateSoundBanks -forceAssetSync   (= Wwise Picker import + Generate Sound Data)
  2. a Python script creates PDA_<Song> track assets and points PAL_JukeboxTrack at them
  3. BuildCookRun                          (= File > Package Project)
  4. pakchunk999 is renamed <Mod>CrimeBossAudio and given its own IoStore container ID
"""
import json
import os
import re
import shutil
import subprocess

from . import config

TRACKS_ROOT = "/Game/JukeboxMod/Tracks"           # must match the editor plugin
EVENTS_ROOT = "/Game/WwiseAudio/GeneratedSoundData/SoundBanks/Events/Default_Work_Unit/Jukebox"
NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)


def log(msg=""):
    print(msg, flush=True)


class Engine:
    def __init__(self, modkit_uproject):
        self.modkit_project_dir = os.path.dirname(os.path.abspath(modkit_uproject))
        self.modkit_uproject = modkit_uproject
        self.root = os.path.normpath(os.path.join(self.modkit_project_dir, "..", "UnrealEngine", "Engine"))
        self.editor_cmd = os.path.join(self.root, "Binaries", "Win64", "UE4Editor-Cmd.exe")
        self.uat = os.path.join(self.root, "Binaries", "DotNET", "AutomationTool.exe")
        for p in (self.editor_cmd, self.uat):
            if not os.path.isfile(p):
                raise RuntimeError("Mod Kit engine file not found: " + p)
        self.wwise_plugin = os.path.join(self.modkit_project_dir, "Plugins", "Wwise")
        if not os.path.isdir(self.wwise_plugin):
            raise RuntimeError("The Mod Kit's Wwise plugin was not found at " + self.wwise_plugin)


def _run(cmd, log_path, cwd=None):
    with open(log_path, "w", encoding="utf-8", errors="replace") as f:
        res = subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT, cwd=cwd, creationflags=NO_WINDOW)
    return res.returncode


def _log_errors(log_path, limit=15):
    out = []
    with open(log_path, encoding="utf-8", errors="replace") as f:
        for ln in f:
            if re.search(r"(Error:|^ERROR|Traceback|Fatal error)", ln) and "LogInit: Display" not in ln:
                out.append(ln.rstrip()[:300])
    return out[:limit]


def _patch_ini(path, edits):
    """edits: list of (regex, replacement) or ('section', header, line) inserts."""
    with open(path, encoding="utf-8-sig") as f:
        s = f.read()
    for e in edits:
        if e[0] == "insert":
            _, header, line = e
            if line not in s:
                s = s.replace(header, header + "\r\n" + line, 1) if header in s else s + "\r\n" + header + "\r\n" + line + "\r\n"
        else:
            s = re.sub(e[0], lambda m: e[1], s)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(s)


def ensure_audio_project(work, mod, wproj, engine, wwise_root):
    """Create (or refresh) Output/<Mod>/AudioProject from the guide's template."""
    proj = os.path.join(work, "AudioProject")
    uproject = os.path.join(proj, "CrimeBoss.uproject")   # must stay "CrimeBoss" (game paths)
    template = os.path.join(config.THIRD_PARTY_DIR, "JukeboxTemplate", "JukeboxTemplate")
    jukebox_mod = os.path.join(config.THIRD_PARTY_DIR, "JukeboxTransfer", "Mods", "JukeboxMod")
    if not os.path.isdir(template) or not os.path.isdir(jukebox_mod):
        raise RuntimeError("Template files missing in ThirdParty\\ - run Setup.bat again.")

    if not os.path.isfile(uproject):
        log("  creating the audio project (one time)...")
        shutil.copytree(template, proj, ignore=shutil.ignore_patterns("Mods"))
    # Always refresh the plugins so Mod Kit updates are picked up.
    for name, src in (("Wwise", engine.wwise_plugin), ("JukeboxMod", jukebox_mod)):
        dst = os.path.join(proj, "Plugins", name)
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        shutil.copytree(src, dst, ignore=shutil.ignore_patterns("Intermediate", "Saved"))

    with open(engine.modkit_uproject, encoding="utf-8-sig") as f:
        assoc = json.load(f).get("EngineAssociation", "")
    with open(uproject, "w", encoding="utf-8") as f:
        json.dump({"FileVersion": 3, "EngineAssociation": assoc, "Category": "",
                   "Description": "Jukebox audio project for {} (generated by Jukebox Builder)".format(mod),
                   "Plugins": [{"Name": n, "Enabled": True} for n in
                               ("Wwise", "JukeboxMod", "PythonScriptPlugin", "EditorScriptingUtilities")]},
                  f, indent="\t")

    rel_wproj = os.path.relpath(wproj, proj).replace("\\", "/")
    _patch_ini(os.path.join(proj, "Config", "DefaultGame.ini"), [
        (r'WwiseProjectPath=\(FilePath="[^"]*"\)', 'WwiseProjectPath=(FilePath="{}")'.format(rel_wproj)),
        (r'StagingDirectory=\(Path="[^"]*"\)', 'StagingDirectory=(Path="")'),
        ("insert", "[/Script/UnrealEd.ProjectPackagingSettings]", '+DirectoriesToNeverCook=(Path="/JukeboxMod")'),
    ])
    # Distance-field build notifications crash headless (-nullrhi) runs; music doesn't need them.
    _patch_ini(os.path.join(proj, "Config", "DefaultEngine.ini"), [
        (r"r\.GenerateMeshDistanceFields=\w+", "r.GenerateMeshDistanceFields=False"),
    ])
    with open(os.path.join(proj, "Config", "DefaultEditorPerProjectUserSettings.ini"), "w", newline="\r\n") as f:
        f.write("[/Script/AkAudio.AkSettingsPerUser]\nWwiseWindowsInstallationPath=(Path=\"{}\")\n"
                "AutoConnectToWAAPI=False\n".format(wwise_root.replace("\\", "/")))
    return uproject


def _clean(proj):
    for rel in (r"Content\WwiseAudio", r"Content\JukeboxMod\Tracks", r"Saved\Cooked", r"Saved\StagedBuilds"):
        shutil.rmtree(os.path.join(proj, rel), ignore_errors=True)


def _editor(engine, uproject, extra, log_path):
    cmd = [engine.editor_cmd, uproject, "-unattended", "-nosplash", "-nullrhi", "-nop4", "-stdout",
           "-FullStdOutLogOutput"] + extra
    return _run(cmd, log_path)


def build_audio_pak(mod, work, wproj, songs, engine, wwise_root, set_container_id):
    proj_file = ensure_audio_project(work, mod, wproj, engine, wwise_root)
    proj = os.path.dirname(proj_file)
    logs = os.path.join(work, "logs")
    os.makedirs(logs, exist_ok=True)
    _clean(proj)

    log("  importing Wwise sound data into Unreal...")
    lp = os.path.join(logs, "1_sound_data.log")
    code = _editor(engine, proj_file, ["-run=GenerateSoundBanks", "-platforms=Windows", "-forceAssetSync"], lp)
    events_dir = os.path.join(proj, "Content", *EVENTS_ROOT.split("/")[2:])
    missing = [s.event_name for s in songs if not os.path.isfile(os.path.join(events_dir, s.event_name + ".uasset"))]
    if code != 0 or missing:
        raise RuntimeError("Generating sound data failed (missing: {}). See {}\n{}".format(
            ", ".join(missing) or "-", lp, "\n".join(_log_errors(lp))))

    log("  creating track assets (PDA_...)...")
    job = os.path.join(work, "audio_job.json")
    with open(job, "w", encoding="utf-8") as f:
        json.dump({"mod": mod, "tracks_root": TRACKS_ROOT, "events_root": EVENTS_ROOT,
                   "songs": [{"id": s.id, "display_name": s.display_name, "event": s.event_name} for s in songs],
                   "result": os.path.join(work, "audio_job_result.json")}, f, indent=2)
    script = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ue_scripts", "audio_assets.py")
    os.environ["JUKEBOX_JOB"] = job
    lp = os.path.join(logs, "2_track_assets.log")
    code = _editor(engine, proj_file, ["-run=pythonscript", "-script=" + script], lp)
    result_path = os.path.join(work, "audio_job_result.json")
    if code != 0 or not os.path.isfile(result_path):
        raise RuntimeError("Creating the track assets failed. See {}\n{}".format(lp, "\n".join(_log_errors(lp))))
    with open(result_path, encoding="utf-8") as f:
        result = json.load(f)
    os.remove(result_path)
    if result.get("errors"):
        raise RuntimeError("Creating the track assets failed:\n" + "\n".join(result["errors"]))

    log("  cooking and packaging the audio (this is the slow part)...")
    lp = os.path.join(logs, "3_package.log")
    code = _run([engine.uat, "BuildCookRun", "-project=" + proj_file, "-noP4", "-platform=Win64",
                 "-clientconfig=Development", "-cook", "-stage", "-pak", "-iostore", "-compressed",
                 "-nocompile", "-nocompileeditor", "-nodebuginfo", "-unattended", "-utf8output"],
                lp, cwd=os.path.dirname(engine.uat))
    paks = os.path.join(proj, "Saved", "StagedBuilds", "WindowsNoEditor", "CrimeBoss", "Content", "Paks")
    src = {e: os.path.join(paks, "pakchunk999-WindowsNoEditor." + e) for e in ("pak", "ucas", "utoc")}
    if code != 0 or not all(os.path.isfile(p) for p in src.values()):
        raise RuntimeError("Packaging the audio failed (exit {}). See {}\n{}".format(code, lp, "\n".join(_log_errors(lp))))

    # Sanity check: every track asset and event must be inside the chunk.
    with open(src["utoc"], "rb") as f:
        toc = f.read()
    absent = [n for s in songs for n in ("PDA_" + s.id, s.event_name) if (n + ".uasset").encode() not in toc]
    if absent:
        raise RuntimeError("The audio pak is missing: " + ", ".join(absent))

    out_dir = os.path.join(work, "AudioPak")
    shutil.rmtree(out_dir, ignore_errors=True)
    os.makedirs(out_dir)
    base = mod + "CrimeBossAudio"   # same naming as working jukebox mods
    for e, p in src.items():
        shutil.copy2(p, os.path.join(out_dir, "{}.{}".format(base, e)))
    utoc = os.path.join(out_dir, base + ".utoc")
    res = subprocess.run([set_container_id, utoc], capture_output=True, text=True, creationflags=NO_WINDOW)
    if res.returncode != 0:
        raise RuntimeError("set_container_id failed:\n" + res.stdout + res.stderr)
    size = os.path.getsize(os.path.join(out_dir, base + ".ucas"))
    log("  audio pak ready: {}  ({:.1f} MB)".format(out_dir, size / 1048576))
    return out_dir
